const translationIndex = { en: 0, es: 1, ru: 2 } as const;

export function translatorFor(locale: Locale): Translator {
  return (text, ...values) => {
    const translated = locale === 'pt-BR' || !Object.hasOwn(translations, text)
      ? text
      : translations[text][translationIndex[locale]];
    return translated.replace(/\{(\d+)\}/g, (key, index) => String(values[Number(index)] ?? key));
  };
}
